            Title = "2. 路由表各字段详解",
            Body = """
【目标网络 + 前缀长度/掩码】要去的网段。0.0.0.0/0（掩码 0.0.0.0）= 所有地址 = 默认路由；192.168.1.0/24（掩码 255.255.255.0）= 一个 C 类网段。前缀越长越具体，优先级越高。

【网关（下一跳）】数据要转交给的“中转站”。两种取值：
  · 具体网关 IP（如 192.168.1.1）：目标在别的网段，先把包交给网关（通常是路由器）转发；
  · “在链路上(on-link)”：目标就在本网卡所在网段，直接 ARP 找到对方发过去，不需要网关。

【接口（if）】从哪块网卡发出。即 route print 第一列的接口索引。多网卡机器上，接口与网关必须匹配（网关得在该网卡自己的网段里），否则路由无效。

【跃点数 Metric】同一目的地有多条路由时用来“分高下”的代价分：越小越优先。实际生效的跃点 = 接口跃点（网卡的属性，可在网卡 IPv4 高级设置里改）+ 路由跃点（添加路由时指定的值）。route print 显示的是两者之和。跃点相同的两条同目标路由会形成等价多路径(ECMP)，行为不直观，应避免。

【协议来源】这条路由是谁写的：本地(接口配 IP 自动生成)、DHCP 下发(常见于默认网关)、手动 route add/本工具(NetMgmt)、ICMP 重定向等。来源决定它“会不会被系统自动改回去”——例如手动删掉 DHCP 下发的默认路由后，租约刷新时可能会回来。

【持久路由(route add -p)】写入注册表、重启后依然生效的路由；不勾持久则是临时路由，重启即消失。备份会把两种都记下来。
