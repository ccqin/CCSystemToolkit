            Body = """
给网卡配置 IP 192.168.1.233/24 后，系统应当自动生成 192.168.1.0/24 → 在链路上 的直连路由。它声明“这个网段的设备就接在本网卡上”。

如果这条路由缺失（常见于：手动挂了多个 IP、网卡驱动异常、某些 VPN 软件清表），发往 192.168.1.x 的包匹配不到直连路由，就会掉进默认路由。若默认路由是代理隧道的 TUN 网卡，这些内网流量会被全部塞进代理——表现为：挂上代理后，内网设备 Ping 不通、工控设备连不上、NAS 访问超时。

