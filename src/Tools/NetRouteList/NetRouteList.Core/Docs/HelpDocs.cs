            Body = """
路由表是 Windows 的“导航地图”：你要访问的每一个 IP（每台设备、每个网站）都属于某个网段，系统发送数据前会查路由表，决定三件事——从哪块网卡出去（接口）、要不要经过网关（下一跳）、如果多条路都能走选哪条（跃点数）。

查表规则是“最长前缀匹配”：谁的目标网段掩得最具体（前缀最长），就走谁。例如路由表里同时有 0.0.0.0/0（默认路由）和 192.168.1.0/24，那么访问 192.168.1.50 时走 192.168.1.0/24 这条，因为它更具体；访问 114.114.114.114 时两条都“匹配”，但只有 0.0.0.0/0 兜底，于是走默认路由。

Windows 会自动维护这张表：配置 IP 时生成直连路由、DHCP 下发默认网关、VPN 软件插入自己的路由。本工具做的事情，就是让这张表“看得见、改得动、可备份”。
