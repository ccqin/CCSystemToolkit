            Body = """
默认路由是兜底规则：“前面所有具体路由都没匹配上的流量，都走我这里”。它通常指向宽频路由器或代理隧道，也就是俗话说的“上网出口”。

多块网卡各有一个网关时，就会出现多条默认路由。Windows 不会“同时走”，而是选总跃点最小的那条，其余只是备份。因此：
  · 想让某块网卡作为上网出口 → 调小它的跃点或删掉其它默认路由；
  · 只想让某网卡访问特定内网、不走它的网关上网 → 删掉它的默认路由，只留具体网段路由；
  · 代理/VPN 软件的 TUN 虚拟网卡常以跃点 0/1 插入默认路由，从而接管全部流量——这是“挂了代理全部流量都进隧道”的机制。
