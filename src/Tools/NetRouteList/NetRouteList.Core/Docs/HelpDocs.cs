            Body = """
Q：加了路由却不生效？
A：① 检查跃点：更具体的路由本应无条件优先，但如果加了等价路由且跃点更大，可能仍走旧的；② 路由的目标/掩码/接口要匹配真实流量；③ 代理软件(TUN)可能在拦截，把目标网段加入其直连规则。

Q：重启后手动加的路由不见了？
A：添加时没勾“持久路由”。临时路由重启即失；勾上持久（等价 route add -p）后写入注册表。

Q：跃点相同的两条路由会怎样？
A：形成等价多路径，系统可能在两者间分流，行为不直观。建议错开跃点。

Q：删除路由后它自己又回来了？
A：来源是 DHCP 或系统自动生成（Local）的路由会被自动重建。要真正去掉 DHCP 默认网关，需要在网卡设置里改，或用更具体的路由覆盖。

Q：备份能跨机器用吗？
A：可以导入，但只有“网卡名称能对上”的条目才会恢复（工具会按名称重映射）。建议先在目标机把网卡名与 IP 配置一致。

Q：RouteDump / 命令行？
A：tools 目录附带 RouteDump 控制台程序，可在命令行直接导出路由表、网卡与诊断结果，便于留档对比。
