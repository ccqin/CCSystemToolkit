            Body = """
【备份】把当前完整路由表（IPv4 全部 + IPv6 全部）连同网卡快照（名称、IP、网关、接口索引）序列化为 JSON 文件，保存在 %LOCALAPPDATA%\NetRouteList\backups。这是“纯快照”，不会改动系统。

【恢复 · 增量合并】只把“备份里有、当前没有”的路由补回来；已存在的条目若跃点不同会更新，其余一概不动。适合：迁移配置、修复被改乱的个别路由。风险低。

【恢复 · 完全恢复】让路由表与备份完全一致：补缺失、删多余（只删“手动添加”类来源的系统可管理路由，系统/DHCP 自动生成的会跳过并说明）、改差异。适合：把机器恢复到已知良好状态。改动大，请先保留安全快照。

【安全快照】每次恢复前，工具会自动先把“恢复前的当前状态”存为一个备份（备注里标明由来）。恢复出了问题，再用它恢复回去即可。

【接口重映射】重启或增删网卡后接口索引会变。恢复时如果备份里的索引对不上，工具会按“网卡名称”自动重映射到当前索引；网卡已不存在的条目会跳过并在报告里说明。

注意：备份记录的是“路由”，不是网卡的 IP 配置本身。恢复路由要求对应网卡与 IP 已就位（例如先按备份里的网卡快照把 IP 配好），否则那些网段的路由会跳过。
